"""promtool unit tests for the generated rules: the alerts fire on a fast burn, stay quiet on a
healthy service, and the freshness alert pages when a mart misses its contract time."""

from __future__ import annotations

from typing import Any

import yaml

from apr import conf
from apr.contracts.model import by_name
from apr.slo.rules import camel, late_after_seconds, prometheus_rules


def _annotations(alert: str) -> dict[str, str]:
    for g in prometheus_rules()["groups"]:
        for r in g["rules"]:
            if r.get("alert") == alert:
                return r["annotations"]
    raise KeyError(alert)


def tests() -> dict[str, Any]:
    cfg = conf.read("slo")
    ok = 'apr_gateway_requests_total{lane="fast",role="analyst",outcome="ok"}'
    err = 'apr_gateway_requests_total{lane="fast",role="analyst",outcome="engine_error"}'
    refused = 'apr_gateway_requests_total{lane="none",role="product_manager",outcome="refused"}'
    burning = []
    for a in cfg["burn_alerts"]:
        name = f"APR_GatewayAvailability_{camel(a['name'])}"
        burning.append(
            {
                "eval_time": "70m",
                "alertname": name,
                "exp_alerts": [
                    {
                        "exp_labels": {"severity": a["severity"], "slo": "gateway_availability"},
                        "exp_annotations": _annotations(name),
                    }
                ],
            }
        )
    quiet = [
        {"eval_time": "70m", "alertname": f"APR_GatewayAvailability_{camel(a['name'])}", "exp_alerts": []}
        for a in cfg["burn_alerts"]
    ]
    mart = by_name("daily_trading")
    late = late_after_seconds(mart.freshness.expected_by)
    fresh_series = 'apr_product_data_through_timestamp_seconds{product="daily_trading"}'
    return {
        "rule_files": ["../rules/slo.rules.yaml"],
        "evaluation_interval": "1m",
        "tests": [
            {
                "name": "10% of accepted queries fail: every availability alert fires",
                "interval": "1m",
                "input_series": [{"series": ok, "values": "0+90x120"}, {"series": err, "values": "0+10x120"}],
                "alert_rule_test": burning,
            },
            {
                "name": "0.1% fail and many refusals: refusals are not failures, nothing fires",
                "interval": "1m",
                "input_series": [
                    {"series": ok, "values": "0+999x120"},
                    {"series": err, "values": "0+1x120"},
                    {"series": refused, "values": "0+400x120"},
                ],
                "alert_rule_test": quiet,
            },
            {
                "name": "daily_trading has no data for yesterday after its contract time: page",
                "interval": "1m",
                "input_series": [{"series": fresh_series, "values": "0x2100"}],
                "alert_rule_test": [
                    {"eval_time": f"{(late - 600) // 60}m", "alertname": "APR_ProductLate", "exp_alerts": []},
                    {
                        "eval_time": f"{(late + 900) // 60}m",
                        "alertname": "APR_ProductLate",
                        "exp_alerts": [
                            {
                                "exp_labels": {"severity": "page", "product": "daily_trading", "team": mart.owner.team},
                                "exp_annotations": {
                                    "summary": f"{mart.table} has no data for yesterday after "
                                    f"{mart.freshness.expected_by} UTC",
                                    "contact": mart.owner.contact,
                                    "runbook": "docs/runbooks/late_data.md",
                                },
                            }
                        ],
                    },
                ],
            },
        ],
    }


def write_tests() -> str:
    p = conf.path("deploy", "prometheus", "tests", "slo.test.yaml")
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(
        "# Generated by `apr generate`. Run: promtool test rules deploy/prometheus/tests/slo.test.yaml\n"
        + yaml.safe_dump(tests(), sort_keys=False, width=200),
        encoding="utf-8",
    )
    return str(p)
