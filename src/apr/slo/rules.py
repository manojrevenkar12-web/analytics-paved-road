"""Prometheus recording and alerting rules generated from config/slo.yaml, and the same
burn-rate arithmetic in Python for the simulator and the drills, so what the drills report is
what Prometheus would page on."""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any

import yaml

from apr import conf
from apr.contracts.model import all_contracts

UNITS = {"m": 60, "h": 3600, "d": 86400}


def seconds(w: str) -> int:
    m = re.fullmatch(r"(\d+)([mhd])", w)
    assert m, w
    return int(m.group(1)) * UNITS[m.group(2)]


def windows(cfg: dict[str, Any]) -> list[str]:
    ws = {f"{cfg['window_days']}d"}
    for a in cfg["burn_alerts"]:
        ws |= {a["long"], a["short"]}
    return sorted(ws, key=seconds)


def prometheus_rules(cfg: dict[str, Any] | None = None) -> dict[str, Any]:
    cfg = cfg or conf.read("slo")
    groups = []
    for name, o in cfg["objectives"].items():
        rec: list[dict[str, Any]] = []
        for w in windows(cfg):
            good, total = o["good"].replace("{{window}}", w), o["total"].replace("{{window}}", w)
            rec.append({"record": f"slo:apr_{name}:error_ratio{w}", "expr": f"1 - ({good}) / ({total})"})
        budget = 1 - o["objective"]
        rec.append(
            {
                "record": f"slo:apr_{name}:budget_remaining",
                "expr": f"1 - slo:apr_{name}:error_ratio{cfg['window_days']}d / {budget:g}",
            }
        )
        alerts: list[dict[str, Any]] = []
        for a in cfg["burn_alerts"]:
            thr = a["burn"] * budget
            alerts.append(
                {
                    "alert": f"APR_{camel(name)}_{camel(a['name'])}",
                    "expr": (
                        f"slo:apr_{name}:error_ratio{a['long']} > {thr:.6g} and "
                        f"slo:apr_{name}:error_ratio{a['short']} > {thr:.6g}"
                    ),
                    "labels": {"severity": a["severity"], "slo": name},
                    "annotations": {
                        "summary": f"{o['description']}: error budget burning {a['burn']}x",
                        "runbook": f"docs/runbooks/{name}.md",
                    },
                }
            )
        groups.append({"name": f"slo-{name}", "rules": rec + alerts})
    # freshness, per data product: one series per product, 1 if the day's batch was on time
    f = cfg["freshness"]["metric"]
    rec = []
    alerts = []
    for c in all_contracts().values():
        sel = f'{f}{{product="{c.name}"}}'
        rec.append(
            {
                "record": "slo:apr_product_freshness:error_ratio30d",
                "expr": f"1 - avg_over_time({sel}[30d])",
                "labels": {"product": c.name},
            }
        )
        alerts.append(
            {
                "alert": "APR_ProductLate",
                "expr": f'time() - apr_product_data_through_timestamp_seconds{{product="{c.name}"}} > '
                f"{late_after_seconds(c.freshness.expected_by)}",
                "for": "10m",
                "labels": {
                    "severity": "page" if c.layer == "mart" else "ticket",
                    "product": c.name,
                    "team": c.owner.team,
                },
                "annotations": {
                    "summary": f"{c.table} has no data for yesterday after {c.freshness.expected_by} UTC",
                    "contact": c.owner.contact,
                    "runbook": "docs/runbooks/late_data.md",
                },
            }
        )
    groups.append({"name": "slo-freshness", "rules": rec + alerts})
    return {"groups": groups}


def late_after_seconds(expected_by: str) -> int:
    """Seconds after the end of a business day by which its batch must be published."""
    h, m = map(int, expected_by.split(":"))
    return 86400 + h * 3600 + m * 60


def camel(s: str) -> str:
    return "".join(p.capitalize() for p in s.split("_"))


def write_rules() -> str:
    p = conf.path("deploy", "prometheus", "rules", "slo.rules.yaml")
    p.parent.mkdir(parents=True, exist_ok=True)
    text = "# Generated by `apr generate` from config/slo.yaml and the contracts. Do not edit.\n" + yaml.safe_dump(
        prometheus_rules(), sort_keys=False, width=200
    )
    p.write_text(text, encoding="utf-8")
    return str(p)


# ---- the same arithmetic over simulated per-minute counts --------------------------------


@dataclass
class BurnAlert:
    name: str
    severity: str
    start_min: int
    end_min: int | None


def burn_alerts(
    good: list[float], total: list[float], objective: float, cfg: dict[str, Any] | None = None, step_s: int = 60
) -> list[BurnAlert]:
    """Per-step counts in, alert intervals out (inclusive start, exclusive end)."""
    cfg = cfg or conf.read("slo")
    import numpy as np

    g, t = np.asarray(good, float), np.asarray(total, float)
    cg, ct = np.concatenate([[0], np.cumsum(g)]), np.concatenate([[0], np.cumsum(t)])
    budget = 1 - objective
    out: list[BurnAlert] = []
    n = len(g)
    for a in cfg["burn_alerts"]:
        lw, sw = seconds(a["long"]) // step_s, seconds(a["short"]) // step_s
        idx = np.arange(1, n + 1)

        def ratio(w: int, idx: Any = idx) -> Any:
            lo = np.maximum(idx - w, 0)
            tot = ct[idx] - ct[lo]
            bad = tot - (cg[idx] - cg[lo])
            return np.where(tot > 0, bad / np.maximum(tot, 1e-12), 0.0)

        firing = (ratio(lw) > a["burn"] * budget) & (ratio(sw) > a["burn"] * budget)
        start = None
        for i, f in enumerate(firing):
            if f and start is None:
                start = i
            elif not f and start is not None:
                out.append(BurnAlert(a["name"], a["severity"], start, i))
                start = None
        if start is not None:
            out.append(BurnAlert(a["name"], a["severity"], start, None))
    return out


def budget_remaining(good: float, total: float, objective: float) -> float:
    if total <= 0:
        return 1.0
    return 1 - ((total - good) / total) / (1 - objective)
