"""The paved road: everything a data product needs is generated from its contract, so a team
writes one YAML file and gets the table, the dbt tests, the Airflow DAG, the dashboard and the
alerts, all consistent with each other."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml

from apr import conf
from apr.contracts.model import Contract, all_contracts

DBT_TYPES = {
    "string": "varchar",
    "long": "bigint",
    "double": "double",
    "date": "date",
    "timestamp": "timestamp",
    "boolean": "boolean",
}


def dbt_schema(contracts: dict[str, Contract] | None = None) -> dict[str, Any]:
    models = []
    for c in (contracts or all_contracts()).values():
        if c.build.kind != "dbt":
            continue
        cols = []
        for col in c.columns:
            tests: list[Any] = []
            if not col.nullable:
                tests.append("not_null")
            if col.unique:
                tests.append("unique")
            if col.accepted:
                tests.append({"accepted_values": {"arguments": {"values": col.accepted}}})
            entry: dict[str, Any] = {
                "name": col.name,
                "data_type": DBT_TYPES[col.type],
                "meta": {"classification": col.classification},
            }
            if tests:
                entry["data_tests"] = tests
            cols.append(entry)
        models.append(
            {
                "name": c.build.model,
                "description": c.description,
                "config": {"contract": {"enforced": True}, "meta": {"owner": c.owner.team, "product": c.name}},
                "columns": cols,
            }
        )
    return {"version": 2, "models": models}


def write_dbt_schema() -> Path:
    p = conf.path("transform", "models", "marts", "_contracts.yml")
    header = "# Generated by `apr generate` from config/products/*.yaml. Do not edit.\n"
    p.write_text(header + yaml.safe_dump(dbt_schema(), sort_keys=False), encoding="utf-8")
    return p


def grafana_dashboard(contracts: dict[str, Contract] | None = None) -> dict[str, Any]:
    """One dashboard: gateway SLOs on top, then one freshness row per data product."""
    panels: list[dict[str, Any]] = []
    y = 0

    def panel(title: str, expr: str, unit: str, x: int, w: int = 8, kind: str = "timeseries", legend: str = ""):
        nonlocal panels
        panels.append(
            {
                "type": kind,
                "title": title,
                "gridPos": {"x": x, "y": y, "w": w, "h": 7},
                "datasource": {"type": "prometheus", "uid": "prometheus"},
                "fieldConfig": {"defaults": {"unit": unit}},
                "targets": [{"expr": expr, "legendFormat": legend, "refId": "A"}],
            }
        )

    panel("Availability, 30 days", "1 - slo:apr_gateway_availability:error_ratio30d", "percentunit", 0, kind="stat")
    panel("Error budget left", "slo:apr_gateway_availability:budget_remaining", "percentunit", 8, kind="stat")
    panel("Queries by lane", "sum by (lane) (rate(apr_gateway_requests_total[5m]))", "reqps", 16, legend="{{lane}}")
    y += 7
    panel(
        "p95 latency by lane",
        "histogram_quantile(0.95, sum by (le, lane) (rate(apr_gateway_query_duration_seconds_bucket[5m])))",
        "s",
        0,
        legend="{{lane}}",
    )
    panel("Refusals by rule", "sum by (rule) (rate(apr_gateway_refusals_total[1h]))", "reqps", 8, legend="{{rule}}")
    panel(
        "Cache hit ratio",
        'sum(rate(apr_gateway_cache_total{result="hit"}[1h])) / sum(rate(apr_gateway_cache_total[1h]))',
        "percentunit",
        16,
    )
    y += 7
    for c in (contracts or all_contracts()).values():
        panel(
            f"{c.name}: data age",
            f'time() - apr_product_data_through_timestamp_seconds{{product="{c.name}"}}',
            "s",
            0,
            w=12,
            legend=c.owner.team,
        )
        panel(
            f"{c.name}: on time, 30 days",
            f'1 - slo:apr_product_freshness:error_ratio30d{{product="{c.name}"}}',
            "percentunit",
            12,
            w=12,
            kind="stat",
        )
        y += 7
    return {
        "title": "Analytics paved road",
        "uid": "apr-overview",
        "schemaVersion": 39,
        "tags": ["generated"],
        "time": {"from": "now-7d", "to": "now"},
        "panels": panels,
    }


def write_grafana() -> Path:
    p = conf.path("deploy", "grafana", "dashboards", "paved-road.json")
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(grafana_dashboard(), indent=2) + "\n", encoding="utf-8")
    return p
